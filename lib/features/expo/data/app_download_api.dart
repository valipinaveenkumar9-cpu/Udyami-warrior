import 'dart:convert';
import 'dart:typed_data';
import 'package:http/http.dart' as http;
import 'package:uk_circle_partners/core/utils/network_utils.dart';
import 'package:uk_circle_partners/core/utils/session_manager.dart';

/// QR + tracked link + counters returned by GET /app-download/qr.
class AppDownloadInfo {
  final String playStoreUrl;

  /// The Warrior's unique referral code (cpId); null until the Ward Chairman approves.
  final String? referralCode;
  final Uint8List qrPng;
  final int totalDownloads;
  final int todayDownloads;

  const AppDownloadInfo({
    required this.playStoreUrl,
    required this.referralCode,
    required this.qrPng,
    required this.totalDownloads,
    required this.todayDownloads,
  });
}

/// A person who registered in UB Kutumba using this Warrior's referral code.
/// Only name + location are exposed.
class ReferredUser {
  final String name;
  final String? location;
  final DateTime? registeredAt;

  const ReferredUser({required this.name, this.location, this.registeredAt});
}

class AppDownloadApi {
  static String get _baseUrl => NetworkUtils.baseUrl;

  static Map<String, String> _headers() {
    final token = SessionManager.token;
    return {
      'Content-Type': 'application/json',
      if (token != null) 'Authorization': 'Bearer $token',
    };
  }

  /// GET /app-download/qr  (QR image is generated by the backend)
  static Future<AppDownloadInfo?> getQr() async {
    try {
      final res = await http
          .get(Uri.parse('$_baseUrl/app-download/qr'), headers: _headers())
          .timeout(const Duration(seconds: 20));
      if (res.statusCode != 200) return null;
      final body = jsonDecode(res.body) as Map<String, dynamic>;
      final dataUrl = (body['qrDataUrl'] ?? '').toString();
      final comma = dataUrl.indexOf(',');
      if (comma < 0) return null;
      return AppDownloadInfo(
        playStoreUrl: body['playStoreUrl'].toString(),
        referralCode: body['referralCode']?.toString(),
        qrPng: base64Decode(dataUrl.substring(comma + 1)),
        totalDownloads: (body['totalDownloads'] ?? 0) as int,
        todayDownloads: (body['todayDownloads'] ?? 0) as int,
      );
    } catch (_) {
      return null;
    }
  }

  /// GET /app-download/referrals -> who registered with my referral code
  static Future<List<ReferredUser>?> getReferrals() async {
    try {
      final res = await http
          .get(Uri.parse('$_baseUrl/app-download/referrals'), headers: _headers())
          .timeout(const Duration(seconds: 20));
      if (res.statusCode != 200) return null;
      final body = jsonDecode(res.body) as Map<String, dynamic>;
      return ((body['data'] ?? []) as List)
          .map((e) => ReferredUser(
                name: (e['name'] ?? '').toString(),
                location: e['location']?.toString(),
                registeredAt: DateTime.tryParse((e['registeredAt'] ?? '').toString())?.toLocal(),
              ))
          .toList();
    } catch (_) {
      return null;
    }
  }

  /// GET /app-download/stats  -> total and today counts
  static Future<({int total, int today})?> getStats() async {
    try {
      final res = await http
          .get(Uri.parse('$_baseUrl/app-download/stats'), headers: _headers())
          .timeout(const Duration(seconds: 15));
      if (res.statusCode != 200) return null;
      final body = jsonDecode(res.body) as Map<String, dynamic>;
      return (
        total: (body['totalDownloads'] ?? 0) as int,
        today: (body['todayDownloads'] ?? 0) as int,
      );
    } catch (_) {
      return null;
    }
  }
}
